import { apiClient } from './apiClient';
import { ApiEndpoints } from '../constants/api';
import { storage } from './storage';
import {
  PlatformModulePublicConfig,
  PlatformThemeControlConfig,
  PlatformLanguageControlConfig,
} from './configService';

export interface MasterAdminLoginRequest {
  usernameOrEmail: string;
  password?: string;
  totpCode?: string;
  recoveryCode?: string;
}

export interface MasterAdminUserDto {
  id: number;
  mobileNumber: string;
  fullName?: string;
  email?: string;
  roles: string[];
  isTotpEnabled: boolean;
  lastLoginAt?: string;
}

export interface MasterAdminLoginResponse {
  success: boolean;
  message: string;
  token?: string;
  requiresMfaEnrollment: boolean;
  tempEnrollmentToken?: string;
  user?: MasterAdminUserDto;
}

export interface MasterAdminTotpSetupResponse {
  secretKey: string;
  manualEntryKey: string;
  authenticatorUri: string;
  qrCodeUrl: string;
  recoveryCodes: string[];
  message?: string;
  accountLabel?: string;
  issuer?: string;
}

export interface MasterAdminPlatformConfig {
  modules: PlatformModulePublicConfig[];
  theme: PlatformThemeControlConfig;
  language: PlatformLanguageControlConfig;
  systemSettings: Record<string, string>;
  lastUpdatedAt: string;
  updatedByAdmin?: string;
}

export const masterAdminService = {
  /**
   * Primary Master Admin login requiring Email/Password + Authenticator (TOTP) or Recovery Code.
   */
  async login(request: MasterAdminLoginRequest): Promise<MasterAdminLoginResponse> {
    const res = await apiClient.post<any>(
      ApiEndpoints.masterAdmin.auth.login,
      request
    );
    const data = (res?.data || res) as MasterAdminLoginResponse;
    if (data.token) {
      await storage.setToken(data.token);
      await storage.setMasterAdminMfaVerified(true);
    }
    return data;
  },

  /**
   * Request new TOTP Authenticator registration key and backup recovery codes.
   */
  async setupTotp(mfaEnrollmentToken?: string): Promise<MasterAdminTotpSetupResponse> {
    const headers: Record<string, string> = {};
    if (mfaEnrollmentToken) {
      headers['X-MFA-Token'] = mfaEnrollmentToken;
    }
    const res = await apiClient.post<any>(
      ApiEndpoints.masterAdmin.auth.setupTotp,
      {},
      { headers }
    );
    const data = res.data?.data || res.data || res;
    const rawSecret = data.secretKey || data.manualEntryKey || '';
    const rawUri = data.qrCodeUri || data.authenticatorUri || '';
    return {
      secretKey: rawSecret,
      manualEntryKey: rawSecret,
      authenticatorUri: rawUri,
      qrCodeUrl: rawUri,
      recoveryCodes: data.recoveryCodes || [],
      message: data.message,
      accountLabel: data.accountLabel,
      issuer: data.issuer || 'Zupify',
    };
  },

  /**
   * Confirm TOTP enrollment by providing the 6-digit code generated by the Authenticator app.
   */
  async confirmTotp(
    totpCode: string,
    secretKey: string,
    mfaEnrollmentToken?: string
  ): Promise<{ success: boolean; message: string; token?: string }> {
    const headers: Record<string, string> = {};
    if (mfaEnrollmentToken) {
      headers['X-MFA-Token'] = mfaEnrollmentToken;
    }
    const res = await apiClient.post<any>(
      ApiEndpoints.masterAdmin.auth.confirmTotp,
      { totpCode, secretKey },
      { headers }
    );
    const data = res.data || res;
    if (data.token) {
      await storage.setToken(data.token);
      await storage.setMasterAdminMfaVerified(true);
    }
    return data;
  },

  /**
   * Check MFA status for the currently authenticated Master Admin.
   */
  async getStatus(): Promise<{
    userId: number;
    fullName?: string;
    email?: string;
    isTotpEnabled: boolean;
    hasRecoveryCodes: boolean;
  }> {
    const res = await apiClient.get<any>(ApiEndpoints.masterAdmin.auth.status);
    return res.data?.data || res.data || res;
  },

  /**
   * Fetch complete Master Admin platform configuration.
   */
  async getConfig(): Promise<MasterAdminPlatformConfig> {
    const res = await apiClient.get<any>(ApiEndpoints.masterAdmin.config.get);
    return res.data?.data || res.data || res;
  },

  /**
   * Update module visibility and display sequence.
   */
  async updateModules(
    modules: PlatformModulePublicConfig[]
  ): Promise<MasterAdminPlatformConfig> {
    const res = await apiClient.put<any>(
      ApiEndpoints.masterAdmin.config.updateModules,
      { modules }
    );
    return res.data?.data || res.data || res;
  },

  /**
   * Update theme controls (allowUserThemeSwitch and defaultTheme).
   */
  async updateTheme(
    theme: PlatformThemeControlConfig
  ): Promise<MasterAdminPlatformConfig> {
    const res = await apiClient.put<any>(
      ApiEndpoints.masterAdmin.config.updateTheme,
      theme
    );
    return res.data?.data || res.data || res;
  },

  /**
   * Update language controls (allowUserLanguageSwitch, supportedLanguages, defaultLanguage).
   */
  async updateLanguage(
    language: PlatformLanguageControlConfig
  ): Promise<MasterAdminPlatformConfig> {
    const res = await apiClient.put<any>(
      ApiEndpoints.masterAdmin.config.updateLanguage,
      language
    );
    return res.data?.data || res.data || res;
  },

  /**
   * Update extensible system feature flags and settings.
   */
  async updateSettings(
    settings: Record<string, string>
  ): Promise<MasterAdminPlatformConfig> {
    const res = await apiClient.put<any>(
      ApiEndpoints.masterAdmin.config.updateSettings,
      { settings }
    );
    return res.data?.data || res.data || res;
  },

  /**
   * End Master Admin privileged session.
   */
  async logout(): Promise<void> {
    await storage.setMasterAdminMfaVerified(false);
  },
};
